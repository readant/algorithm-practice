// 引入输入输出流头文件，提供 cin、cout 等工具
#include <iostream>

// 使用标准命名空间，这样可以直接写 cout，而不必写成 std::cout
// 通俗来说：std 就像一个大盒子，里面装着 cout、cin 等工具，
// 加上这一句后，我们就省去了每次都要写 "std::" 的麻烦。
using namespace std;

// 主函数，程序从这里开始执行
int main() {
    // 向标准输出（屏幕）打印字符串 "Hello,World!"
    // cout 是输出流对象，<< 是插入运算符，将右侧的内容送入输出流
    // 字符串必须用双引号括起来，且内容严格区分大小写
    cout << "Hello,World!" << '\n';
    // '\n' 是换行符，相当于按下回车键，让后续输出从下一行开始
    // 注意：这里不使用 endl，因为 endl 除了换行还会强制刷新缓冲区，
    // 在输出大量数据时会影响性能，而 '\n' 只换行，速度更快。

    // 返回 0 表示程序正常结束，这是一个约定俗成的写法
    return 0;
}
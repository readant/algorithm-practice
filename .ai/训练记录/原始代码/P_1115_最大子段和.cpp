// Kadane 卡登算法：复用前面已经算好的结果，不要重复计算
#include<iostream>
using namespace std;
// int的范围：-2147483648~2147483647

int n,a,b,i,ans=-2147483647;  // ans初始为int能存的最小上限附近

// - ans 预留空间，专门应对全是负数的测试用例
// - ans为什么不初始化为0，如果所有数字如果所有数字都是负数，0 会错误输出，而我们要选出最大的那个负数。
// - 全局变量：自动放在静态内存，不是栈内存，开大变量不容易栈溢出
int main(){
    cin>>n;
    for(i=1;i<=n;i++){
        cin>>a;
        // 读一个丢一个，不保存整个数组

        if(i==1) b=a;  // 第一个元素，只能自己单独作为子段 ，b = a 


        //  Kadane 核心递推公式
        // a + b 把当前数字a接在上端最优子段后面
        // a 抛弃前面所有，从当前a 新开一段
        // max 二选一，哪个更大，b就取哪个
        else b = max(a,a+b); 
        ans = max(ans,b);
    }
    cout<<ans;
    return 0;
}



